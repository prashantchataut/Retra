#!/bin/sh
# Assembles the Retra replacement BIOS and regenerates ../bios_image.h.
# Requires arm-none-eabi-as / arm-none-eabi-ld / arm-none-eabi-objcopy (host tools only;
# the generated header is committed so Android builds do not need them).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
arm-none-eabi-as -mcpu=arm7tdmi -o "$TMP/bios.o" "$HERE/retra_bios.S"
arm-none-eabi-ld -Ttext=0 -o "$TMP/bios.elf" "$TMP/bios.o"
arm-none-eabi-objcopy -O binary "$TMP/bios.elf" "$TMP/bios.bin"
python3 -I - "$TMP/bios.bin" "$HERE/../bios_image.h" <<'EOF'
import sys
data = open(sys.argv[1], 'rb').read()
assert len(data) <= 0x4000, len(data)
out = ['// Generated by bios/build_bios.sh from bios/retra_bios.S - do not edit.',
       '#pragma once', '#include "common.h"', 'namespace retra {',
       'static const u8 kRetraBios[%d] = {' % len(data)]
for i in range(0, len(data), 16):
    out.append('    ' + ', '.join('0x%02X' % b for b in data[i:i+16]) + ',')
out.append('};')
out.append('}  // namespace retra')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print('BIOS image: %d bytes' % len(data))
EOF
