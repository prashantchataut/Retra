def glyphs():
    out = {}
    for d in (G, SPECIAL):
        for ch, v in d.items():
            rows = v.split("|")
            assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
            out[ch] = ["....."] + rows
    return out
