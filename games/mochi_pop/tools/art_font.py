# printable ASCII 32..126 maps to tiles 0..94 (unknown chars -> blank)
CHARS = [chr(c) for c in range(32, 127)]


def glyph_layer(ch):
    L = Layer(8, 8)
    rows = G.get(ch, G[" "]).split("|")
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                L.set(x + 1, y, 1)
    # drop shadow (right, down, down-right)
    sh = []
    for y in range(8):
        for x in range(8):
            if L.px[y][x] == 0 and (L.get(x - 1, y) == 1 or L.get(x, y - 1) == 1 or L.get(x - 1, y - 1) == 1):
                sh.append((x, y))
    for x, y in sh:
        L.px[y][x] = 2
    return L


def font_layers():
    return [glyph_layer(ch) for ch in CHARS]
