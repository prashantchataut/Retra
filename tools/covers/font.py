FOLD = {"É": "E", "é": "E", "µ": "U", "Ü": "U", "ü": "U"}


def clean(text):
    return "".join(FOLD.get(ch, ch) for ch in text.upper() if FOLD.get(ch, ch).upper() in G or ch in FOLD)


def width(text, s):
    return len(text) * 6 * s - s if text else 0


def draw(cv, text, x, y, s, fill_top, fill_bottom, outline, shadow=None):
    """Draws text at scale s with a 1 px outline and an optional 1 px drop shadow."""
    text = clean(text)
    top, bot, ol = hexc(fill_top), hexc(fill_bottom), hexc(outline)
    on = set()
    for i, ch in enumerate(text):
        for gy, row in enumerate(G[ch]):
            for gx, bit in enumerate(row):
                if bit == "#":
                    for sy in range(s):
                        for sx in range(s):
                            on.add((x + i * 6 * s + gx * s + sx, y + gy * s + sy))
    rim = set()
    for (px_, py_) in on:
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                p = (px_ + dx, py_ + dy)
                if p not in on:
                    rim.add(p)
    if shadow:
        sh = hexc(shadow)
        for (px_, py_) in on | rim:
            p = (px_ + 1, py_ + 2)
            if p not in on and p not in rim:
                cv.put(p[0], p[1], sh)
    for p in rim:
        cv.put(p[0], p[1], ol)
    h = 7 * s
    for (px_, py_) in on:
        t = (py_ - y) / max(1, h - 1)
        c = mix(top, bot, 1 if t > 0.55 else 0) if s > 1 else top
        if s > 1 and (py_ - y) % (7 * s) < s and t < 0.2:
            c = mix(top, (255, 255, 255), 0.45)
        cv.put(px_, py_, c)


def title_block(cv, lines, x, y, fills, outline, shadow, max_w=224, kicker=None, kicker_color=None, align="left"):
    """Lays out a title: optional small kicker line, then 1-2 big lines (scale 3 if it fits, else 2)."""
    big = [clean(l) for l in lines]
    s = 3 if all(width(l, 3) <= max_w for l in big) else 2
    cy = y
    if kicker:
        k = clean(kicker)
        kx = x if align == "left" else (240 - width(k, 1)) // 2
        draw(cv, k, kx, cy, 1, kicker_color or fills[0], kicker_color or fills[0], outline, shadow)
        cy += 10
    for l in big:
        lx = x if align == "left" else (240 - width(l, s)) // 2
        draw(cv, l, lx, cy, s, fills[0], fills[1], outline, shadow)
        cy += 7 * s + 4
    return cy
