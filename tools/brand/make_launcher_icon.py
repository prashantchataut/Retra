#!/usr/bin/env python3
"""Generates Retra's adaptive launcher icon layers (vector drawables) from Mochi's geometry.

Mochi's body is the same superellipse as the in-app mascot (ui/components/Mochi.kt), sampled and
turned into a smooth Catmull-Rom -> cubic Bezier outline, then shaded with layered gradients
(form shadow, rim/bounce light, specular highlight) so the icon reads soft and round, not flat.

    python3 tools/brand/make_launcher_icon.py   # rewrites app/src/main/res/drawable/ic_launcher_*.xml
"""
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable")

K = 0.64  # Mochi's 100-unit design box -> 108 dp icon canvas (66 dp safe zone)


def X(x):
    return 54 + (x - 50) * K


def Y(y):
    return 54 + (y - 57) * K


def f(v):
    s = "%.2f" % v
    return s.rstrip("0").rstrip(".") if "." in s else s


def body_points(n=40):
    cx, cy, a, top, bottom, p = 50, 62, 38, 33, 28, 2.4
    pts = []
    for i in range(n):
        th = i / n * 2 * math.pi
        c, s = math.cos(th), math.sin(th)
        x = cx + a * math.copysign(abs(c) ** (2 / p), c)
        ry = top if s < 0 else bottom
        y = cy + ry * math.copysign(abs(s) ** (2 / p), s)
        pts.append((X(x), Y(y)))
    return pts


def smooth_closed(pts):
    """Closed Catmull-Rom spline through pts as cubic Bezier path data."""
    n = len(pts)
    d = ["M%s,%s" % (f(pts[0][0]), f(pts[0][1]))]
    for i in range(n):
        p0, p1, p2, p3 = pts[(i - 1) % n], pts[i], pts[(i + 1) % n], pts[(i + 2) % n]
        c1 = (p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6)
        c2 = (p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6)
        d.append("C%s,%s %s,%s %s,%s" % tuple(f(v) for v in (*c1, *c2, *p2)))
    return " ".join(d) + "Z"


def ellipse(cx, cy, rx, ry):
    return "M%s,%s a%s,%s 0,1 0,%s,0 a%s,%s 0,1 0,%s,0Z" % (
        f(cx - rx), f(cy), f(rx), f(ry), f(2 * rx), f(rx), f(ry), f(-2 * rx))


def lin(x1, y1, x2, y2, stops):
    items = "".join('\n                <item android:offset="%s" android:color="%s"/>' % (f(o), c) for o, c in stops)
    return ('\n        <aapt:attr name="android:fillColor">\n            <gradient android:type="linear" '
            'android:startX="%s" android:startY="%s" android:endX="%s" android:endY="%s">%s\n            </gradient>\n'
            '        </aapt:attr>' % (f(x1), f(y1), f(x2), f(y2), items))


def rad(cx, cy, r, stops):
    items = "".join('\n                <item android:offset="%s" android:color="%s"/>' % (f(o), c) for o, c in stops)
    return ('\n        <aapt:attr name="android:fillColor">\n            <gradient android:type="radial" '
            'android:centerX="%s" android:centerY="%s" android:gradientRadius="%s">%s\n            </gradient>\n'
            '        </aapt:attr>' % (f(cx), f(cy), f(r), items))


def path(d, fill=None, grad=None, stroke=None, width=None, extra=""):
    attrs = 'android:pathData="%s"' % d
    if fill:
        attrs += ' android:fillColor="%s"' % fill
    if stroke:
        attrs += ' android:strokeColor="%s" android:strokeWidth="%s" android:strokeLineCap="round" android:strokeLineJoin="round"' % (stroke, f(width))
    attrs += extra
    if grad:
        return "    <path %s>%s\n    </path>\n" % (attrs, grad)
    return "    <path %s/>\n" % attrs


HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- %s Generated by tools/brand/make_launcher_icon.py. -->\n'
          '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
          '    xmlns:aapt="http://schemas.android.com/aapt"\n'
          '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n')


def leaf_paths():
    stem = "M%s,%s Q%s,%s %s,%s" % (f(X(50)), f(Y(33)), f(X(50.5)), f(Y(27)), f(X(53)), f(Y(24)))
    leaf = "M%s,%s C%s,%s %s,%s %s,%s C%s,%s %s,%s %s,%sZ" % (
        f(X(52)), f(Y(25)), f(X(54)), f(Y(13)), f(X(66)), f(Y(9)), f(X(75)), f(Y(12)),
        f(X(73)), f(Y(22)), f(X(63)), f(Y(29)), f(X(52)), f(Y(25)))
    vein = "M%s,%s Q%s,%s %s,%s" % (f(X(54)), f(Y(24)), f(X(63)), f(Y(19)), f(X(71)), f(Y(13.5)))
    return stem, leaf, vein


def foreground():
    body = smooth_closed(body_points())
    stem, leaf, vein = leaf_paths()
    out = HEADER % "Mochi, Retra's mascot: launcher foreground (66 dp safe zone)."
    # Soft ground shadow: a radial gradient squashed into an ellipse.
    out += ('    <group android:pivotX="%s" android:pivotY="%s" android:scaleY="0.16">\n' % (f(X(50)), f(Y(93))))
    out += "    " + path(ellipse(X(50), Y(93), 22, 22), grad=rad(X(50), Y(93), 22, [(0, "#4D1F4A3C"), (0.6, "#261F4A3C"), (1, "#001F4A3C")]))
    out += "    </group>\n"
    out += path(stem, stroke="#FF3D8A58", width=1.6)
    out += path(leaf, grad=lin(X(55), Y(12), X(70), Y(26), [(0, "#FFC8F7B0"), (1, "#FF5FC26E")]), stroke="#FF3D8A58", width=1.3)
    out += path(vein, stroke="#8C3D8A58", width=0.85)
    # Body: base colour ramp, then form shading, bounce light and a top-left glow.
    out += path(body, grad=lin(54, Y(29), 54, Y(90), [(0, "#FFFFDCE7"), (0.45, "#FFF9B3C9"), (1, "#FFEC8CA8")]))
    out += path(body, grad=rad(X(41), Y(50), 33, [(0, "#00D9708F"), (0.62, "#00D9708F"), (1, "#8CC95A80")]))
    out += path(body, grad=lin(54, Y(76), 54, Y(90), [(0, "#00FFF6EC"), (1, "#73FFF6EC")]))
    out += path(body, grad=rad(X(35), Y(41), 17, [(0, "#B3FFFFFF"), (1, "#00FFFFFF")]))
    out += path(body, stroke="#FF6E2F57", width=1.5)
    # Specular highlight.
    out += ('    <group android:pivotX="%s" android:pivotY="%s" android:rotation="-24">\n' % (f(X(32)), f(Y(42))))
    out += "    " + path(ellipse(X(31.5), Y(42), 7.5 * K, 3.4 * K), grad=lin(X(31.5), Y(38.6), X(31.5), Y(45.4), [(0, "#F2FFFFFF"), (1, "#80FFFFFF")]))
    out += "    </group>\n"
    out += path(ellipse(X(43), Y(37.5), 1.8 * K, 1.8 * K), fill="#CCFFFFFF")
    # Face.
    for bx in (27.5, 72.5):
        out += path(ellipse(X(bx), Y(68.75), 6.2 * K, 3.4 * K), grad=rad(X(bx), Y(68.75), 6.2 * K, [(0, "#B3FF7B9C"), (1, "#00FF7B9C")]))
    for ex in (38, 62):
        out += path(ellipse(X(ex), Y(60), 3.7 * K, 4.9 * K), fill="#FF35203F")
        out += path(ellipse(X(ex + 1.3), Y(57.9), 2.1 * K, 2.1 * K), fill="#FFFFFFFF")
        out += path(ellipse(X(ex - 1.6), Y(62.3), 1.0 * K, 1.0 * K), fill="#D9FFFFFF")
    smile = "M%s,%s Q%s,%s %s,%s Q%s,%s %s,%s" % (
        f(X(45)), f(Y(67)), f(X(47.5)), f(Y(70.5)), f(X(50)), f(Y(67.5)), f(X(52.5)), f(Y(70.5)), f(X(55)), f(Y(67)))
    out += path(smile, stroke="#FFB8486A", width=1.45)
    return out + "</vector>\n"


def background():
    out = HEADER % "Mint glass tile behind Mochi."
    full = "M0,0h108v108h-108z"
    out += path(full, grad=lin(14, 0, 94, 108, [(0, "#FFEAFBF4"), (0.5, "#FFC9EFDF"), (1, "#FFBFE2F2")]))
    out += path(full, grad=rad(54, 62, 44, [(0, "#73FFE3EC"), (0.55, "#33FFE3EC"), (1, "#00FFE3EC")]))
    out += path("M0,0h108v50c-32,-13 -72,-7 -108,9z", grad=lin(54, 0, 54, 58, [(0, "#99FFFFFF"), (1, "#00FFFFFF")]))
    return out + "</vector>\n"


def monochrome():
    body = smooth_closed(body_points())
    _, leaf, _ = leaf_paths()
    eyes = " ".join(ellipse(X(ex), Y(60), 3.7 * K, 4.9 * K) for ex in (38, 62))
    out = HEADER % "Themed (monochrome) icon: Mochi's silhouette with eyes cut out."
    out += path(body + " " + eyes, fill="#FF000000", extra=' android:fillType="evenOdd"')
    out += path(leaf, fill="#FF000000")
    out += path("M%s,%s Q%s,%s %s,%s" % (f(X(50)), f(Y(33)), f(X(50.5)), f(Y(27)), f(X(53)), f(Y(24))), stroke="#FF000000", width=1.6)
    return out + "</vector>\n"


for name, fn in (("ic_launcher_foreground", foreground), ("ic_launcher_background", background), ("ic_launcher_monochrome", monochrome)):
    with open(os.path.join(OUT, name + ".xml"), "w") as fh:
        fh.write(fn())
    print("wrote", name)
